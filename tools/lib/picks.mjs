import path from 'node:path';
import { pickRows, toPosix, localDay } from './vault.mjs';
import { joinList, cmp, domainOrder, domainTitle } from './rules.mjs';

export const projectName = root => path.basename(String(root ?? '')) || 'unknown project';
// Resolved only when absolute, so a row with no project, or a relative one, reads the same from any folder.
const projectKey = root => (typeof root === 'string' && path.isAbsolute(root) ? toPosix(root) : String(root ?? '')).toLowerCase();
export const sameProject = (a, b) => projectKey(a) === projectKey(b);

const day = r => localDay(r.at);

// Rows from before pick.mjs carry no subject, so they back rules but aren't anyone's decision on a piece of work.
export const subjectRows = (rows = pickRows()) => rows.filter(r => typeof r.subject === 'string' && r.subject && typeof r.domain === 'string');

// A row stops being live once a later row replaces or confirms it.
export function laterRows(rows) {
  const later = new Map();
  for (const r of rows) {
    for (const how of ['replaces', 'confirms']) if (typeof r[how] === 'string') later.set(r[how], { id: r.id, day: day(r), how });
  }
  return later;
}

export const endedBy = by => `${by.how === 'replaces' ? 'replaced by' : 'confirmed as'} ${by.id}`;

export const newestFirst = rows => [...rows].sort((a, b) => cmp(String(b.at ?? ''), String(a.at ?? '')) || cmp(String(a.id), String(b.id)));

const isComment = r => typeof r.text === 'string';
const statusWord = r => (r.status === 'provisional' ? 'provisional' : r.confirms ? 'confirmed' : 'user');

function over(r) {
  const others = (Array.isArray(r.options) ? r.options : []).map(o => o?.label).filter(l => typeof l === 'string' && l !== r.pick);
  return others.length ? ` over ${joinList(others.map(l => `"${l}"`), 'and')}` : '';
}

export function entry(r, { sheet, later, indent }) {
  const head = isComment(r)
    ? `- ${day(r)} · comment: "${r.text}" (${r.id})`
    : `- ${day(r)} · ${statusWord(r)} · ${r.question}: "${r.pick}"${over(r)} (${r.id})`;
  const by = later?.get(r.id);
  const details = [
    r.notes && `The user said: "${r.notes}"`,
    r.reason && `Agent's reason: ${r.reason}`,
    by && `${by.how === 'replaces' ? 'Replaced' : 'Confirmed'} by ${by.id} on ${by.day}.`,
    r.sheet && sheet(r),
  ].filter(Boolean);
  return [head, ...details.map(l => `${indent}${l}`)];
}

export function renderDecisions(rows = subjectRows()) {
  const out = ['# Decisions', '', 'Generated by tools/build.mjs from the picks in raw/picks/. Do not edit.'];
  if (!rows.length) out.push('', 'No picks yet.');
  const later = laterRows(rows);
  const embed = r => `![${r.subject}](${r.sheet})`;
  for (const d of domainOrder(rows.map(r => r.domain))) {
    out.push('', `## ${d} · ${domainTitle(d)}`);
    const mine = rows.filter(r => r.domain === d);
    const projects = [...new Map(mine.map(r => [projectKey(r.project), r.project])).entries()]
      .sort(([a, x], [b, y]) => cmp(projectName(x), projectName(y)) || cmp(a, b));
    for (const [key, root] of projects) {
      out.push('', `### ${projectName(root)}`);
      const inProject = mine.filter(r => projectKey(r.project) === key);
      for (const s of [...new Set(inProject.map(r => r.subject))].sort(cmp)) {
        out.push('', `#### ${s}`, '');
        for (const r of newestFirst(inProject.filter(x => x.subject === s))) out.push(...entry(r, { sheet: embed, later, indent: '  - ' }));
      }
    }
  }
  return `${out.join('\n')}\n`;
}
